CREATE TABLE operation_log (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    request_method VARCHAR(16) COMMENT '请求方法 GET/POST/PUT/DELETE',
    request_uri VARCHAR(512) COMMENT '请求 URI',
    client_ip VARCHAR(64) COMMENT '客户端 IP',
    client_id VARCHAR(128) COMMENT '客户端标识 X-Client-Id',
    user_id VARCHAR(128) COMMENT '用户标识 X-User-Id',
    request_params TEXT COMMENT '请求参数 JSON',
    request_headers VARCHAR(512) COMMENT '请求头摘要 JSON',
    response_status VARCHAR(16) COMMENT '响应状态 SUCCESS/FAIL/ERROR',
    response_code VARCHAR(32) COMMENT '响应码',
    response_data TEXT COMMENT '响应数据 JSON（截断存储）',
    error_message VARCHAR(512) COMMENT '异常信息',
    module VARCHAR(128) COMMENT '所属模块',
    operation_type VARCHAR(32) COMMENT '操作类型 QUERY/CREATE/UPDATE/DELETE',
    description VARCHAR(512) COMMENT '操作描述',
    execution_time BIGINT COMMENT '执行耗时 (ms)',
    trace_id VARCHAR(128) COMMENT '链路追踪 ID X-Trace-Id',
    request_from VARCHAR(64) COMMENT '请求来源 X-Request-From',
    api_version VARCHAR(32) COMMENT 'API 版本 X-Api-Version',
    service_name VARCHAR(64) COMMENT '服务名称',
    create_time DATETIME COMMENT '记录创建时间',
    KEY idx_create_time (create_time),
    KEY idx_module (module),
    KEY idx_trace_id (trace_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='操作日志审计表';